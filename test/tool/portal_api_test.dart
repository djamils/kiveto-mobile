      expect(git.calls, [
        [backend.path, 'rev-parse', '--git-dir'],
        [backend.path, 'rev-parse', '--verify', '--quiet', '840dbead^{commit}'],
        [backend.path, 'show', '$_commit:openapi/portal.v1.yaml'],
      ]);
