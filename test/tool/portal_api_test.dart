/// SHA-256 of `<path>\n<sha256>\n` over [files] in sorted path order: the
/// documented `inputs` / `files` digests, computed independently.
String _digestOf(Map<String, List<int>> files) {
  final paths = files.keys.toList()..sort();
  return sha256Hex(
    utf8.encode(
      [for (final path in paths) '$path\n${sha256Hex(files[path]!)}\n'].join(),
    ),
  );
}

final class _Repo {
  new() : root = Directory.systemTemp.createTempSync('kiveto_portal_api_') {
    addTearDown(() => root.deleteSync(recursive: true));
  }

  /// A repository synced at [_commit], generated and stamped.
  static Future<_Repo> generated() async {
    final repo = _Repo()
      ..writeBytes(_contract, _contractBytes)
      ..write(
        _source,
        '# comment: ignored\n'
        'repository: https://github.com/djamils/kiveto\n'
        'commit: $_commit\n'
        'sha256: ${sha256Hex(_contractBytes)}\n',
      );
    _inputs.forEach(repo.write);
    _package.forEach(repo.write);
    final stamped = await repo.run(['stamp']);
    expect(stamped.code, 0, reason: stamped.err);
    return repo;
  }

  final Directory root;

  String path(String relative) => '${root.path}/$relative';

  void write(String relative, String content) =>
      writeBytes(relative, utf8.encode(content));

  void writeBytes(String relative, List<int> bytes) {
    File(path(relative))
      ..createSync(recursive: true)
      ..writeAsBytesSync(bytes);
  }

  void append(String relative, String content) =>
      File(path(relative)).writeAsStringSync(content, mode: FileMode.append);

  void delete(String relative) =>
      FileSystemEntity.typeSync(path(relative)) ==
          FileSystemEntityType.directory
      ? Directory(path(relative)).deleteSync(recursive: true)
      : File(path(relative)).deleteSync();

  bool exists(String relative) =>
      FileSystemEntity.typeSync(path(relative)) !=
      FileSystemEntityType.notFound;

  String read(String relative) => File(path(relative)).readAsStringSync();

  /// The `key: value` lines of the CONTRACT stamp.
  Map<String, String> stamp() => {
    for (final line in LineSplitter.split(read(_stampPath)))
      if (!line.startsWith('#')) line.split(': ')[0]: line.split(': ')[1],
  };

  Future<_Result> run(List<String> args, {GitRunner? git}) async {
    final out = StringBuffer();
    final err = StringBuffer();
    final code = git == null
        ? await runPortalApi(args, root: root.path, out: out, err: err)
        : await runPortalApi(
            args,
            root: root.path,
            out: out,
            err: err,
            git: git,
          );
    return (code: code, out: out.toString(), err: err.toString());
  }

  /// The problems `check` reports, one per line.
  Future<List<String>> problems() async {
    final result = await run(['check']);
    expect(result.code, 1, reason: result.out);
    expect(result.out, isEmpty);
    return LineSplitter.split(result.err).toList();
  }
}

/// A backend checkout seen through git: refs resolve to commits, and a
/// commit may hold openapi/portal.v1.yaml. Records every call.
final class _FakeGit {
  new({
    this.isCheckout = true,
    this.refs = const {},
    this.contracts = const {},
  });

  final bool isCheckout;
  final Map<String, String> refs;
  final Map<String, List<int>> contracts;
  final calls = <List<String>>[];

  Future<GitResult> call(String dir, List<String> args) async {
    calls.add([dir, ...args]);
    switch (args) {
      case ['rev-parse', '--git-dir']:
        return isCheckout
            ? GitResult(0, utf8.encode('.git\n'), '')
            : const GitResult(128, [], 'fatal: not a git repository');
      case ['rev-parse', '--verify', '--quiet', final spec]:
        final commit = refs[spec.replaceFirst('^{commit}', '')];
        return commit == null
            ? const GitResult(1, [], '')
            : GitResult(0, utf8.encode('$commit\n'), '');
      case ['show', final spec]:
        final [commit, path] = spec.split(':');
        final bytes = path == 'openapi/portal.v1.yaml'
            ? contracts[commit]
            : null;
        return bytes == null
            ? GitResult(128, const [], 'fatal: path $path does not exist')
            : GitResult(0, bytes, '');
      default:
        throw StateError('unexpected git $args');
    }
  }
}

