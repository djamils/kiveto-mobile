    setUp(() {
      backend = Directory.systemTemp.createTempSync('kiveto_backend_');
      addTearDown(() => backend.deleteSync(recursive: true));
    });

    test('copies the bytes at the full commit and writes SOURCE', () async {
      final repo = _Repo();
      final git = _FakeGit(
        refs: {'840dbead': _commit},
        contracts: {_commit: _contractBytes},
      );

      final result = await repo.run([
        'sync',
        backend.path,
        '840dbead',
      ], git: git.call);

      expect(result.code, 0, reason: result.err);
      expect(File(repo.path(_contract)).readAsBytesSync(), _contractBytes);
      final digest = sha256Hex(_contractBytes);
      expect(
        repo.read(_source),
        '# Written by `make api-sync`; checked by `make api-check`. Never '
        'edit.\n'
        'repository: https://github.com/djamils/kiveto\n'
        'path: openapi/portal.v1.yaml\n'
        'commit: $_commit\n'
        'sha256: $digest\n',
