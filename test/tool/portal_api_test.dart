        repo.delete(_source);

        expect(await repo.problems(), ['$_source is missing - fix: $_syncFix']);
      });

      test('a SOURCE without commit', () async {
        final repo = await _Repo.generated();
        repo.write(_source, 'sha256: ${sha256Hex(_contractBytes)}\n');

        expect(await repo.problems(), [
          '$_source names no commit - fix: $_syncFix',
